  Banknote,
  Bookmark,
  Boxes,
  Briefcase,
  Building2,
  Camera,
  Cloud,
  Code,
  Coffee,
  CreditCard,
  Database,
  FileText,
  Fingerprint,
  Gamepad2,
  Globe,
  HardDrive,
  Heart,
  House,
